-- VIZO · Catálogos de valores del SAT (Capa 0)
--
-- POR QUÉ EXISTEN: el XSD de Fr. V Bis no tiene ni una sola `enumeration`.
-- Valida la FORMA (\d{1,2}) pero no el VALOR: un XML puede validar contra el
-- XSD y traer un tipo de desarrollo que no existe. Estos catálogos permiten
-- validar ANTES de generar, en vez de enterarse cuando el portal rechace el
-- aviso.
--
-- FUENTE: hoja "Combos" de la plantilla oficial DesarrollosInmobiliarios_v4_9.xlsm,
-- descargada del SPPLD el 4 de agosto de 2026. Copia auditable en
-- regulatorio/catalogos/din_catalogos.json.
--
-- NO se cargan los códigos postales ni las colonias (139,719 filas de la misma
-- hoja): el CP se valida por patrón y la colonia es texto libre en el XSD.
--
-- Versionados por vigencia igual que todo lo regulatorio: cuando las RCG
-- cambien un catálogo, se cierra la vigencia y se insertan filas nuevas.

create table catalogos_sat (
  id            uuid primary key default gen_random_uuid(),
  actividad_id  uuid references actividades_vulnerables(id),  -- NULL = todas
  catalogo      text not null,      -- 'tipo_desarrollo', 'moneda', ...
  codigo        text not null,
  descripcion   text not null,
  vigente_desde date not null,
  vigente_hasta date,
  created_at    timestamptz not null default now(),
  constraint catalogo_vigencia_coherente
    check (vigente_hasta is null or vigente_hasta >= vigente_desde),
  constraint catalogo_codigo_sin_traslape
    exclude using gist (
      (coalesce(actividad_id, '00000000-0000-0000-0000-000000000000'::uuid)) with =,
      catalogo with =, codigo with =,
      daterange(vigente_desde, vigente_hasta, '[]') with &&
    )
);

create index on catalogos_sat (catalogo, vigente_desde);

comment on table catalogos_sat is
  'Valores cerrados que el XSD no impone. Validar contra el XSD es necesario pero no suficiente.';

alter table catalogos_sat enable row level security;
create policy "catálogo legible" on catalogos_sat
  for select to authenticated using (true);
grant select on catalogos_sat to authenticated;

-- Consultas canónicas "as of", igual que el resto de la Capa 0.
create or replace function app.catalogo_vigente(p_catalogo text, p_fecha date)
returns table (codigo text, descripcion text)
language sql stable set search_path = '' as $$
  select c.codigo, c.descripcion
  from public.catalogos_sat c
  where c.catalogo = p_catalogo
    and daterange(c.vigente_desde, c.vigente_hasta, '[]') @> p_fecha
  order by length(c.codigo), c.codigo;
$$;

create or replace function app.codigo_valido(p_catalogo text, p_codigo text, p_fecha date)
returns boolean
language sql stable set search_path = '' as $$
  select exists (
    select 1 from public.catalogos_sat c
    where c.catalogo = p_catalogo and c.codigo = p_codigo
      and daterange(c.vigente_desde, c.vigente_hasta, '[]') @> p_fecha
  );
$$;

