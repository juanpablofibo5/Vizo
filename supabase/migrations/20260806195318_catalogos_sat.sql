-- ---------------------------------------------------------------------------
-- catalogos_sat es global: se declara exenta de tenant_id
-- ---------------------------------------------------------------------------
-- La aserción app.verificar_tenancy() detectó esta tabla al crearla, que es
-- justo su trabajo: ninguna tabla nueva se queda sin tenant_id por descuido.
-- Es catálogo regulatorio, igual que umbrales o uma_vigencias, así que la
-- excepción se declara aquí, en la misma migración que la crea.
create or replace function app.verificar_tenancy()
returns table (tabla text, problema text)
language sql
stable
set search_path = ''
as $$
  with exentas(nombre) as (
    values ('uma_vigencias'), ('actividades_vulnerables'), ('umbrales'),
           ('campos_expediente'), ('formatos_aviso'), ('parametros_motor'),
           ('catalogos_sat'),
           ('tenants'), ('usuarios'), ('personas')
  )
  select c.relname::text, 'no tiene columna tenant_id y no está en la lista de exentas'
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
    and c.relkind = 'r'
    and c.relname not in (select nombre from exentas)
    and not exists (
      select 1 from pg_attribute a
      where a.attrelid = c.oid and a.attname = 'tenant_id'
        and a.attnum > 0 and not a.attisdropped
    );
$$;

-- ---------------------------------------------------------------------------
-- Verificación: los valores que el MVP necesita sí están
-- ---------------------------------------------------------------------------
do $$
begin
  raise notice 'Catálogos del SAT: % valores en % catálogos',
    (select count(*) from catalogos_sat),
    (select count(distinct catalogo) from catalogos_sat);

  -- El comprador en preventa entra al aviso como tercero tipo 2. Si este
  -- código no existe, el mapeo del caso de uso central está roto.
  if not app.codigo_valido('tipo_tercero', '2', '2026-02-15') then
    raise exception 'Falta el código de tercero "Cliente(s) en Preventa"';
  end if;

  -- Único tipo de operación de la fracción.
  if not app.codigo_valido('tipo_operacion', '1601', '2026-02-15') then
    raise exception 'Falta el tipo de operación 1601 (Aportación a Desarrollos Inmobiliarios)';
  end if;

  -- El aviso de 24 horas YA existe en el formato vigente como prioridad 2.
  if not app.codigo_valido('prioridad', '2', '2026-02-15') then
    raise exception 'Falta la prioridad 2 (24 HORAS CON OPERACIONES)';
  end if;
end;
$$;
